-- ВОССТАНОВЛЕНИЕ ПО БАЗОВОМУ ДАМПУ, а не результат скрипта. Этап вида manual.
-- Версия kz_localize.py, которой собрана база, утеряна. Доступная версия (этап 30) в трёх строках
-- пишет другие названия. Ниже значения, которые фактически стоят в init/10_full.sql:
--   подразделение 20.0.6.        «РгК «Восток»» / «региональное командование «Восток»»
--   подразделение 20.0.6.0.0.2.  «12 мбр» / «12-я механизированная бригада»
--   склад 1                      «Склад регионального командования «Восток» (вышестоящий)»
-- Отключается переменной BASELINE_PATCH=0 в build/run_all.sh; тогда эти три строки останутся такими,
-- какими их делает доступная версия скрипта, и разойдутся с рабочей базой.
\set ON_ERROR_STOP on
UPDATE mil_core.unit SET short_name = 'РгК «Восток»', full_name = 'региональное командование «Восток»'
 WHERE unit_code = '20.0.6.';
UPDATE mil_core.unit SET short_name = '12 мбр', full_name = '12-я механизированная бригада'
 WHERE unit_code = '20.0.6.0.0.2.';
UPDATE mil_core.warehouse SET warehouse_name = 'Склад регионального командования «Восток» (вышестоящий)',
       capacity_note = 'резерв РгК «Восток», все виды'
 WHERE warehouse_id = 1;
